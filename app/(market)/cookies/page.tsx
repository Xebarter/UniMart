function isNumericHeading(line: string) {
  const l = line.trim()
  return /^\d+\.\s+/.test(l) || /^\d+\.\d+\s+/.test(l) || /^\d+\.\d+\.\s+/.test(l)
}

function headingLevel(line: string) {
  const l = line.trim()
  // "3.1 Something" => h3-ish
  if (/^\d+\.\d+\s+/.test(l)) return 3
  // "1. Something" => h2
  return 2
}

function isBulletLine(line: string) {
  const l = line.trim()
  return l.startsWith('- ') || l.startsWith('* ') || l.endsWith(';')
}

function renderTable(lines: string[]) {
  const rows = lines.map((row) => row.split('\t'))
  const header = rows[0] ?? []
  const body = rows.slice(1)
  return (
    <div className="overflow-x-auto">
      <table className="w-full border-separate border-spacing-0 border border-[#e4ece8] text-sm">
        <thead>
          <tr>
            {header.map((cell, idx) => (
              <th key={`${idx}-${cell}`} className="border-b border-[#e4ece8] bg-[#f6fbf9] px-3 py-2 text-left font-semibold text-[#243e39]">
                {cell}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {body.map((row, rIdx) => (
            <tr key={rIdx}>
              {row.map((cell, cIdx) => (
                <td key={`${rIdx}-${cIdx}`} className="border-b border-[#e4ece8] px-3 py-2 text-[#5f746c]">
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

export default function CookiesPage() {
  const lines = cookiePolicyText.replace(/\r\n/g, '\n').split('\n')

  // Skip the title + Last Updated line (we render those in the app header).
  const bodyStartIdx = Math.max(
    0,
    lines.findIndex((l) => l.toLowerCase().startsWith('last updated'))
  )

  const bodyLines = bodyStartIdx >= 0 ? lines.slice(bodyStartIdx + 1) : lines

  const nodes: React.ReactNode[] = []

  let i = 0
  while (i < bodyLines.length) {
    const raw = bodyLines[i] ?? ''
    const line = raw.trim()

    if (!line) {
      i++
      continue
    }

    // Table (tab-separated) blocks
    if (line.includes('\t') && (bodyLines[i + 1] ?? '').includes('\t')) {
      const tableLines: string[] = []
      while (i < bodyLines.length && (bodyLines[i] ?? '').includes('\t') && (bodyLines[i] ?? '').trim()) {
        tableLines.push(bodyLines[i]!)
        i++
      }
      nodes.push(
        <div key={`table-${i}`} className="pt-6">
          {renderTable(tableLines)}
        </div>
      )
      continue
    }

    // Numbered headings like "1. What Are Cookies?" and "3.1 Strictly Necessary Cookies"
    if (isNumericHeading(line)) {
      const level = headingLevel(line)
      const HeadingTag = level === 3 ? 'h3' : 'h2'
      nodes.push(
        <div key={`h-${i}`} className="space-y-4 border-t border-[#e4ece8] pt-6">
          <HeadingTag className={level === 3 ? 'font-display text-lg font-bold text-[#29463f]' : 'font-display text-xl font-bold text-[#29463f]'}>
            {line}
          </HeadingTag>
        </div>
      )
      i++
      continue
    }

    // Bullet lists (a run of lines that end with ';' or start with '-'/'*')
    if (isBulletLine(line)) {
      const items: string[] = []
      while (i < bodyLines.length) {
        const t = (bodyLines[i] ?? '').trim()
        if (!t || !isBulletLine(t)) break
        items.push(t.replace(/^[*-]\s+/, '').replace(/;$/, ''))
        i++
      }
      nodes.push(
        <ul key={`ul-${i}`} className="list-disc space-y-2 pl-5">
          {items.map((item, idx) => (
            <li key={`${i}-${idx}`}>{item}</li>
          ))}
        </ul>
      )
      continue
    }

    // Paragraphs: gather until blank line or next heading/bullet/table.
    const parts: string[] = []
    while (i < bodyLines.length) {
      const t = (bodyLines[i] ?? '').trim()
      if (!t) break
      if (isNumericHeading(t) || isBulletLine(t) || (t.includes('\t') && (bodyLines[i + 1] ?? '').includes('\t'))) break
      parts.push(t)
      i++
    }
    if (parts.length) {
      nodes.push(
        <p key={`p-${i}`} className="leading-7">
          {parts.join(' ')}
        </p>
      )
    }
  }

  return (
    <div className="mx-auto max-w-[760px] px-5 py-12 sm:px-8 sm:py-16">
      <Link href={marketPaths.home} className="inline-block">
        <BrandLogo showWordmark size={34} wordmarkClassName="text-xl" />
      </Link>

      <h1 className="mt-8 font-display text-[2rem] font-bold tracking-[-0.045em] text-[#243e39] sm:text-[2.5rem]">
        Cookie Policy
      </h1>
      <p className="mt-2 text-sm text-[#8b9994]">Last updated: 18 August 2026</p>

      <div className="mt-8 space-y-6 text-base leading-7 text-[#5f746c]">
        {nodes.map((node, idx) => (
          <div key={idx} className="space-y-4">
            {node}
          </div>
        ))}
      </div>
    </div>
  )
}
