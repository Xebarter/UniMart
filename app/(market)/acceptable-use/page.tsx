function isHeading(line: string) {
  return /^\d+\.\s+/.test(line.trim())
}

function isBulletLine(line: string) {
  const value = line.trim()
  return value.length > 0 && !isHeading(value) && (value.endsWith(';') || value.endsWith('.') || value.endsWith('or') || value.endsWith('and'))
}

export default function AcceptableUsePage() {
  const lines = acceptableUseText.replace(/\r\n/g, '\n').split('\n')
  const lastUpdatedIndex = lines.findIndex((line) =>
    line.toLowerCase().startsWith('last updated:')
  )
  const bodyLines = lastUpdatedIndex >= 0 ? lines.slice(lastUpdatedIndex + 1) : lines

  const content: React.ReactNode[] = []
  let i = 0

  while (i < bodyLines.length) {
    const line = (bodyLines[i] ?? '').trim()

    if (!line) {
      i++
      continue
    }

    if (isHeading(line)) {
      content.push(
        <section key={`section-${i}`} className="space-y-4 border-t border-[#e4ece8] pt-6">
          <h2 className="font-display text-xl font-bold text-[#29463f]">{line}</h2>
        </section>
      )
      i++
      continue
    }

    if (isBulletLine(line)) {
      const items: string[] = []
      while (i < bodyLines.length) {
        const current = (bodyLines[i] ?? '').trim()
        if (!current || isHeading(current) || !isBulletLine(current)) break
        items.push(current.replace(/;$/, ''))
        i++
      }

      content.push(
        <ul key={`list-${i}`} className="list-disc space-y-2 pl-5">
          {items.map((item, index) => (
            <li key={`${i}-${index}`}>{item}</li>
          ))}
        </ul>
      )
      continue
    }

    const paragraphLines: string[] = []
    while (i < bodyLines.length) {
      const current = (bodyLines[i] ?? '').trim()
      if (!current || isHeading(current) || isBulletLine(current)) break
      paragraphLines.push(current)
      i++
    }

    if (paragraphLines.length > 0) {
      content.push(
        <p key={`paragraph-${i}`}>{paragraphLines.join(' ')}</p>
      )
    }
  }

  return (
    <div className="mx-auto max-w-[760px] px-5 py-12 sm:px-8 sm:py-16">
      <Link href={marketPaths.home} className="inline-block">
        <BrandLogo showWordmark size={34} wordmarkClassName="text-xl" />
      </Link>

      <h1 className="mt-8 font-display text-[2rem] font-bold tracking-[-0.045em] text-[#243e39] sm:text-[2.5rem]">
        Acceptable Use Policy
      </h1>
      <p className="mt-2 text-sm text-[#8b9994]">Last updated: 18 August 2026</p>

      <div className="mt-8 space-y-6 text-base leading-7 text-[#5f746c]">
        {content}
      </div>
    </div>
  )
}
